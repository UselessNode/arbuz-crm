// Общие константы модуля pdf-export (во избежание «магических строк»).
export const WORKER_JOB_ARG = '--job';

/**
 * Максимальное время генерации; по истечении воркер принудительно завершается.
 * Значение согласовано с ожиданием на клиенте (`apps/frontend/src/api/pdf-export.ts`):
 * UI опрашивает задание не дольше, чем сервер держит воркер.
 */
export const WORKER_TIMEOUT_MS = 5 * 60 * 1000;

/**
 * Сколько времени задание может висеть в `pending`, не будучи подхваченным воркером.
 * Нужно для восстановления после рестарта сервера: задание, зависшее в `pending`/`processing`
 * дольше этого срока и никем не переведённое в `done`, помечается ошибкой.
 */
export const STALE_JOB_TIMEOUT_MS = WORKER_TIMEOUT_MS + 60 * 1000;
