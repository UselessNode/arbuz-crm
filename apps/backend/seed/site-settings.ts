/** Создаёт настройки для отсутствующих ключей, не трогая уже сохранённые. */
export async function ensureSiteSettings(): Promise<void> {
  const existing = await prisma.site_settings.findMany({ select: { key: true } });
  const present = new Set(existing.map((row) => row.key));
  const missing = SITE_SETTING_KEYS.filter((key) => !present.has(key));
  if (missing.length === 0) return;
  await prisma.site_settings.createMany({
    data: missing.map((key) => ({ key, value: SITE_SETTING_DEFAULTS[key] })),
  });
  log.info('seed: созданы настройки сайта', { created: missing.length });
}
