const DOCUMENTS = [
  { type: ConsentDocumentType.terms, text: USER_AGREEMENT },
  { type: ConsentDocumentType.personal_data_consent, text: PERSONAL_DATA_CONSENT },
] as const;

/** Публикует стартовые редакции документов, если их ещё нет (идемпотентно). */
export async function ensureConsentDocuments(): Promise<void> {
  for (const document of DOCUMENTS) {
    const existing = await prisma.consent_documents.findUnique({
      where: { document_type_version: { document_type: document.type, version: SEED_VERSION } },
      select: { id: true },
    });
    if (existing) continue;
    const created = await prisma.consent_documents.create({
      data: {
        document_type: document.type,
        version: SEED_VERSION,
        text: document.text,
        hash_sha256: hashConsentText(document.text),
      },
      select: { id: true },
    });
    log.info('seed: опубликован документ согласия', { id: created.id, type: document.type, version: SEED_VERSION });
  }
}
